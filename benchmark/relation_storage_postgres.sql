SELECT '# PostgreSQL relation storage DDL microbenchmark';
SELECT '';
SELECT format(
  'PostgreSQL %s, %s-byte pages, %s rows. Measurements follow `VACUUM FULL`.',
  current_setting('server_version'),
  current_setting('block_size'),
  :'rows'
);
SELECT '';
SELECT '| Baseline synchronized row | Domain row + PK | CRDT row + indexes | Total |';
SELECT '| --- | ---: | ---: | ---: |';
WITH baseline AS (
  SELECT
    SUM(CASE WHEN current."objectName" IN (
      'person', 'person_pkey'
    ) THEN current."allocatedBytes" - empty."allocatedBytes" ELSE 0 END) domain,
    SUM(CASE WHEN current."objectName" IN (
      'crdt_data_rows',
      'crdt_data_rows_pkey',
      'crdt_data_rows_scope_tbl_row_idx'
    ) THEN current."allocatedBytes" - empty."allocatedBytes" ELSE 0 END) metadata
  FROM snapshots current
  JOIN snapshots empty ON empty."objectName" = current."objectName"
  WHERE current.stage = 0 AND empty.stage = -1
)
SELECT format(
  '| Insert, no populated relations | %s B | %s B | %s B |',
  round(1.0 * domain / :rows, 2),
  round(1.0 * metadata / :rows, 2),
  round(1.0 * (domain + metadata) / :rows, 2)
)
FROM baseline;

SELECT '';
SELECT '| Added relation | Domain | Field table + indexes | FK table + indexes | CRDT metadata | Focused total |';
SELECT '| ---: | ---: | ---: | ---: | ---: | ---: |';
WITH stage_deltas AS (
  SELECT
    current.stage,
    SUM(CASE WHEN current."objectName" IN (
      'person', 'person_pkey'
    ) THEN current."allocatedBytes" - previous."allocatedBytes" ELSE 0 END) domain,
    SUM(CASE WHEN current."objectName" IN (
      'crdt_data_fields',
      'crdt_data_fields_pkey',
      'crdt_data_fields_row_column_idx'
    ) THEN current."allocatedBytes" - previous."allocatedBytes" ELSE 0 END) field,
    SUM(CASE WHEN current."objectName" IN (
      'crdt_data_foreign_key',
      'crdt_data_foreign_key_pkey',
      'crdt_data_foreign_key_field_idx'
    ) THEN current."allocatedBytes" - previous."allocatedBytes" ELSE 0 END) foreign_key
  FROM snapshots current
  JOIN snapshots previous
    ON previous.stage = current.stage - 1
   AND previous."objectName" = current."objectName"
  WHERE current.stage > 0
  GROUP BY current.stage
)
SELECT format(
  '| %s | %s B | %s B | %s B | %s B | %s B |',
  stage,
  round(1.0 * domain / :rows, 2),
  round(1.0 * field / :rows, 2),
  round(1.0 * foreign_key / :rows, 2),
  round(1.0 * (field + foreign_key) / :rows, 2),
  round(1.0 * (domain + field + foreign_key) / :rows, 2)
)
FROM stage_deltas
ORDER BY stage;

SELECT '';
SELECT '| Object | Allocated / relation |';
SELECT '| --- | ---: |';
WITH object_deltas AS (
  SELECT
    final."objectName",
    final."allocatedBytes" - initial."allocatedBytes" allocated
  FROM snapshots final
  JOIN snapshots initial ON initial."objectName" = final."objectName"
  WHERE final.stage = 3 AND initial.stage = 0
)
SELECT format(
  '| `%s` | %s B |',
  "objectName",
  round(1.0 * allocated / (3 * :rows), 2)
)
FROM object_deltas
ORDER BY CASE "objectName"
  WHEN 'person' THEN 1
  WHEN 'person_pkey' THEN 2
  WHEN 'crdt_data_rows' THEN 3
  WHEN 'crdt_data_rows_pkey' THEN 4
  WHEN 'crdt_data_rows_scope_tbl_row_idx' THEN 5
  WHEN 'crdt_data_fields' THEN 6
  WHEN 'crdt_data_fields_pkey' THEN 7
  WHEN 'crdt_data_fields_row_column_idx' THEN 8
  WHEN 'crdt_data_foreign_key' THEN 9
  WHEN 'crdt_data_foreign_key_pkey' THEN 10
  WHEN 'crdt_data_foreign_key_field_idx' THEN 11
END;

SELECT '';
WITH totals AS (
  SELECT
    SUM(CASE WHEN final."objectName" LIKE 'crdt_data_fields%'
                   OR final."objectName" LIKE 'crdt_data_foreign_key%'
      THEN final."allocatedBytes" - initial."allocatedBytes" ELSE 0 END
    ) metadata,
    SUM(final."allocatedBytes" - initial."allocatedBytes") focused
  FROM snapshots final
  JOIN snapshots initial ON initial."objectName" = final."objectName"
  WHERE final.stage = 3 AND initial.stage = 0
)
SELECT format(
  'Mean per populated relation: **%s B CRDT metadata**, **%s B focused physical total**.',
  round(1.0 * metadata / (3 * :rows), 2),
  round(1.0 * focused / (3 * :rows), 2)
)
FROM totals;

