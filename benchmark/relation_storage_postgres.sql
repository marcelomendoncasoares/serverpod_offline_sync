CREATE SCHEMA relation_storage_benchmark;
SET search_path TO relation_storage_benchmark, pg_catalog;

CREATE FUNCTION relation_storage_bytes(relation REGCLASS)
RETURNS BIGINT
LANGUAGE SQL
AS $$
  SELECT SUM(pg_relation_size(relation, fork_name))
  FROM unnest(ARRAY['main', 'fsm', 'vm', 'init']) fork_name;
$$;

CREATE TABLE person (
  id UUID PRIMARY KEY,
  "scopeId" BIGINT,
  name TEXT NOT NULL,
  surname TEXT,
  "organizationId" UUID,
  "oldCompanyId" UUID,
  "cityId" UUID
);

CREATE TABLE crdt_data_rows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hlcDatetime" TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  "hlcCounter" BIGINT NOT NULL,
  "scopeId" BIGINT NOT NULL,
  "tblId" BIGINT NOT NULL,
  "uuidRowId" UUID NOT NULL,
  "nodeId" BIGINT NOT NULL,
  visibility BIGINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX crdt_data_rows_scope_tbl_row_idx
ON crdt_data_rows ("scopeId", "tblId", "uuidRowId");

CREATE TABLE crdt_data_fields (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hlcDatetime" TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  "hlcCounter" BIGINT NOT NULL,
  "rowId" BIGINT NOT NULL,
  "columnId" BIGINT NOT NULL,
  "nodeId" BIGINT NOT NULL
);

CREATE UNIQUE INDEX crdt_data_fields_row_column_idx
ON crdt_data_fields ("rowId", "columnId");

CREATE TABLE crdt_data_foreign_key (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "fieldId" BIGINT NOT NULL,
  "attemptedValue" UUID,
  "visibleValue" UUID,
  "overrideReason" BIGINT
);

CREATE UNIQUE INDEX crdt_data_foreign_key_field_idx
ON crdt_data_foreign_key ("fieldId");

CREATE TEMP TABLE snapshots (
  stage INTEGER NOT NULL,
  "objectName" TEXT NOT NULL,
  "allocatedBytes" BIGINT NOT NULL,
  PRIMARY KEY (stage, "objectName")
);

